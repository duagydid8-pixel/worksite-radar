import { describe, expect, it } from "vitest";
import { computePersonDetails, getFlaggedPmisOutings } from "./pmisInOutLog";

describe("getFlaggedPmisOutings", () => {
  it("selects technical workers who left before 11:00 or returned at/after 13:00", () => {
    const details = computePersonDetails([
      { 이름: "조기출문", 범주: "기술인", 직종: "배관", 시간: "07:00", 구분: "IN", 회사: "", 일자: "", 출역형태: "" },
      { 이름: "조기출문", 범주: "기술인", 직종: "배관", 시간: "10:59", 구분: "OUT", 회사: "", 일자: "", 출역형태: "" },
      { 이름: "조기출문", 범주: "기술인", 직종: "배관", 시간: "11:20", 구분: "IN", 회사: "", 일자: "", 출역형태: "" },
      { 이름: "늦은복귀", 범주: "기술인", 직종: "용접", 시간: "07:10", 구분: "IN", 회사: "", 일자: "", 출역형태: "" },
      { 이름: "늦은복귀", 범주: "기술인", 직종: "용접", 시간: "11:30", 구분: "OUT", 회사: "", 일자: "", 출역형태: "" },
      { 이름: "늦은복귀", 범주: "기술인", 직종: "용접", 시간: "13:00", 구분: "IN", 회사: "", 일자: "", 출역형태: "" },
      { 이름: "정상외출", 범주: "기술인", 직종: "전기", 시간: "07:20", 구분: "IN", 회사: "", 일자: "", 출역형태: "" },
      { 이름: "정상외출", 범주: "기술인", 직종: "전기", 시간: "11:30", 구분: "OUT", 회사: "", 일자: "", 출역형태: "" },
      { 이름: "정상외출", 범주: "기술인", 직종: "전기", 시간: "12:50", 구분: "IN", 회사: "", 일자: "", 출역형태: "" },
      { 이름: "관리자제외", 범주: "관리자", 직종: "공사관리자", 시간: "07:30", 구분: "IN", 회사: "", 일자: "", 출역형태: "" },
      { 이름: "관리자제외", 범주: "관리자", 직종: "공사관리자", 시간: "10:30", 구분: "OUT", 회사: "", 일자: "", 출역형태: "" },
      { 이름: "관리자제외", 범주: "관리자", 직종: "공사관리자", 시간: "13:20", 구분: "IN", 회사: "", 일자: "", 출역형태: "" },
    ]);

    expect(getFlaggedPmisOutings(details).map((row) => ({
      이름: row.이름,
      outTime: row.outTime,
      inTime: row.inTime,
      reasons: row.reasons,
    }))).toEqual([
      { 이름: "조기출문", outTime: "10:59", inTime: "11:20", reasons: ["11시 이전 출문"] },
      { 이름: "늦은복귀", outTime: "11:30", inTime: "13:00", reasons: ["13시 이후 복귀"] },
    ]);
  });
});
